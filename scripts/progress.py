"""Generate the progress section of README.md and docs/assets/progress.svg. Standard library only.

    python3 -I scripts/progress.py            # print the generated section
    python3 -I scripts/progress.py --write    # rewrite README.md between the markers and docs/assets/progress.svg
    python3 -I scripts/progress.py --check    # exit 1 if README.md or the SVG differs from what --write would write
    python3 -I scripts/progress.py --issues FILE ...   # read issues from a JSON file instead of the GitHub API

The data comes from three places, never from hand edits:

- the task issues (title `AREA-N: ...`) and the open pull requests, read through the `gh` command line tool;
- the phase tables in docs/implementation-plan.md, which put tasks into the development steps of the bar;
- the task table in docs/roadmap.md, for tasks that have no issue yet and as a fallback for sizes.

The README shows one bar with every development step (STEPS below) and a marker on the current one: the first
step whose tasks are not all merged.

Only tasks a maintainer stands behind count: roadmap tasks, and issues that a repository member opened or labelled
`ready` or `claimed`. Issue titles are escaped anyway, because anyone can write them.

A task is `done` when its issue is closed as completed, `in review` when an open, non-draft pull request closes its
issue (`Closes #N`) and was opened by a member or by the task's assignee, `in progress` when it is labelled `claimed`, `ready` when labelled `ready`, and `planned`
otherwise. Issues closed as not planned are left out. Progress is weighted by size: S = 1, M = 3, L = 8.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from xml.sax.saxutils import escape

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
README = "README.md"
SVG = "docs/assets/progress.svg"
ROADMAP = "docs/roadmap.md"
PLAN = "docs/implementation-plan.md"
START = "<!-- progress:start (generated by scripts/progress.py; do not edit by hand) -->"
END = "<!-- progress:end -->"

AREAS = "NET|SRV|IM|DB|SCRIPT|RP|BOT|CLIENT|LAUNCH|OPS|DOC"
TASK_TITLE = re.compile(rf"^((?:{AREAS})-[0-9]+): (.+)$")
CLOSES = re.compile(r"\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s*:?\s+#([0-9]+)\b", re.IGNORECASE)
ROADMAP_ROW = re.compile(rf"^\|\s*((?:{AREAS})-[0-9]+)\s*\|\s*(.+?)\s*\|\s*([SML])\s*\|\s*$")
PLAN_PHASE = re.compile(r"^###\s+Phase\s+([0-9]+)\b")
PLAN_ROW = re.compile(rf"^\|\s*((?:{AREAS})-[0-9]+)(?:\s*\(#[0-9]+\))?\s*\|\s*(.+?)\s*\|")

WEIGHT = {"S": 1, "M": 3, "L": 8}
DEFAULT_SIZE = "M"

# Order matters: the first status in this tuple is the furthest along.
STATUSES = ("done", "in review", "in progress", "ready", "planned")
ICON = {"done": "✅", "in review": "🔍", "in progress": "🛠️", "ready": "🟢", "planned": "⚪"}

# The development steps, in order, on one bar. Each step belongs to a roadmap stage (docs/roadmap.md). A task
