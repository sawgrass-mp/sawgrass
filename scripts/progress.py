STAGE_NAMES = {0: "repository foundation", 1: "server without the game", 2: "roleplay base",
               3: "client in the game", 4: "launcher and releases", 5: "scale"}
TRACK = {"name": "Tooling and docs", "areas": ("OPS", "DOC")}
MARKER = "📍"
LIST_LIMIT = 8  # a step with more tasks than this shows a count instead of the task IDs


def area(task_id):
    return task_id.split("-", 1)[0]


def size_from_labels(labels):
    for label in labels:
        m = re.fullmatch(r"size: ([SML])", label)
        if m:
            return m.group(1)
    return None


def roadmap_tasks(text):
    """{id: (title, size)} from the task table of docs/roadmap.md."""
    tasks = {}
    for line in text.splitlines():
        m = ROADMAP_ROW.match(line.strip())
        if m:
            tasks[m.group(1)] = (m.group(2), m.group(3))
    return tasks


def plan_tasks(text):
    """{id: (phase, title)} from the phase tables of docs/implementation-plan.md, in the plan's order."""
    tasks, phase = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("## "):
            phase = None
        m = PLAN_PHASE.match(line)
        if m:
            phase = int(m.group(1))
            continue
        m = PLAN_ROW.match(line)
        if m and phase is not None:
            tasks.setdefault(m.group(1), (phase, m.group(2)))
    return tasks


def steps_for(plan):
    """STEPS, plus a step for every plan phase that STEPS does not name yet, after the last phase it does name."""
    steps = [dict(s) for s in STEPS]
    named = {s["phase"] for s in steps if "phase" in s}
    for phase in sorted({p for p, _ in plan.values()} - named):
        last = max(i for i, s in enumerate(steps) if "phase" in s)
        steps.insert(last + 1, {"name": f"Plan phase {phase}", "short": f"Phase {phase}",
                                "stage": steps[last]["stage"], "phase": phase,
                                "covers": "See docs/implementation-plan.md"})
    return steps


def step_index(task_id, plan, steps):
    """Index of the task's step in `steps`, or None for the tooling track."""
    if task_id in plan:
        return next(i for i, s in enumerate(steps) if s.get("phase") == plan[task_id][0])
    for i, s in enumerate(steps):
        if area(task_id) in s.get("areas", ()):
            return i
    return None


def labels_of(item):
    return {label["name"] if isinstance(label, dict) else label for label in item.get("labels", [])}


TRUSTED_AUTHORS = {"OWNER", "MEMBER", "COLLABORATOR"}


def trusted_author(item):
    return item.get("author_association") in TRUSTED_AUTHORS


def accepted(item):
    """A maintainer stands behind the issue: they opened it, or labelled it `ready` or `claimed`.

    Anyone can open an issue with a task-like title, even one that reuses a roadmap ID, and close it themselves,
    but only maintainers are repository members and only they add labels. Everything else stays off the README.
    """
    return trusted_author(item) or bool(labels_of(item) & {"ready", "claimed"})


def in_review(issue, pull_requests):
    """A pull request that closes the issue counts if a member or the task's assignee (its claimer) opened it."""
    assignees = {a.get("login") for a in issue.get("assignees") or []}
    return any(trusted_author(p) or (p.get("user") or {}).get("login") in assignees for p in pull_requests)


def collect(items, roadmap, plan=None):
    """Tasks as a list of dicts (id, title, size, status, issue, step), sorted by step and ID.

    `items` are issues as the REST API returns them from /issues (pull requests included, marked by the
    `pull_request` key). `roadmap` is the result of roadmap_tasks(), `plan` of plan_tasks(). A task with an issue
    takes the issue's title, which render_markdown() escapes; a task without an issue takes the roadmap's or the
    plan's (`trusted`). `step` is the index in steps_for(plan), or None for the tooling track.
    """
    plan = plan or {}
    # Issue number -> authors of open, non-draft pull requests that close it.
    closers = {}
    issues = []
    for item in items:
        if "pull_request" in item:
            if item.get("state") == "open" and not item.get("draft"):
                for n in CLOSES.findall(item.get("body") or ""):
                    closers.setdefault(int(n), []).append(item)
            continue
        m = TASK_TITLE.match((item.get("title") or "").strip())
        if not m or not accepted(item):
            continue
        if item.get("state") == "closed" and item.get("state_reason") == "not_planned":
            continue
        issues.append((m.group(1), m.group(2).strip(), item))

    tasks = {}
    for task_id, title, item in issues:
        labels = labels_of(item)
        if item.get("state") == "closed":
            status = "done"
        elif in_review(item, closers.get(item.get("number"), [])):
            status = "in review"
        elif "claimed" in labels:
            status = "in progress"
        elif "ready" in labels:
            status = "ready"
        else:
            status = "planned"
        size = size_from_labels(labels) or roadmap.get(task_id, (None, DEFAULT_SIZE))[1]
        task = {"id": task_id, "title": title, "trusted": False, "size": size, "status": status,
                "issue": item.get("number")}
        # Two issues with one ID: an open one wins over a closed one, so reopened work is not shown as done.
        old = tasks.get(task_id)
        if old is None or (old["status"] == "done" and status != "done"):
            tasks[task_id] = task

    written = {**{i: t for i, (_, t) in plan.items()}, **{i: t for i, (t, _) in roadmap.items()}}
    for task_id, title in written.items():
        if task_id not in tasks:
            size = roadmap.get(task_id, (None, DEFAULT_SIZE))[1]
            tasks[task_id] = {"id": task_id, "title": title, "trusted": True, "size": size, "status": "planned",
                              "issue": None}

    steps = steps_for(plan)
    for t in tasks.values():
        t["step"] = step_index(t["id"], plan, steps)
    areas = [a for s in steps for a in s.get("areas", ())] + list(TRACK["areas"])
    for a in AREAS.split("|"):
        if a not in areas:
            areas.append(a)
    order = list(plan)  # a planned task keeps its place in the plan; the others go by area and number

    def key(t):
        place = order.index(t["id"]) if t["id"] in order else len(order)
        return (len(steps) if t["step"] is None else t["step"], place, areas.index(area(t["id"])),
                int(t["id"].split("-")[1]))

    return sorted(tasks.values(), key=key)


def progress(tasks):
    """(done weight, total weight, percent rounded down)."""
    total = sum(WEIGHT[t["size"]] for t in tasks)
    done = sum(WEIGHT[t["size"]] for t in tasks if t["status"] == "done")
    return done, total, (100 * done // total if total else 0)


def step_rows(tasks, plan=None):
    """One row per step: (step, its tasks, percent done, state text, state key).

    The state key is `done`, `current`, `waiting` or `todo`. The current step is the first one that is not done:
    a step with tasks is done when every one of them is merged, a step without tasks only when its `state` says
    so. So the marker follows what is merged on `main`, not what is planned.
    """
    steps = steps_for(plan or {})
    rows, current_found = [], False
    for i, s in enumerate(steps):
        own = [t for t in tasks if t.get("step") == i]
        _, _, pct = progress(own)
        done = sum(t["status"] == "done" for t in own)
        finished = s.get("state") == "done" or (bool(own) and done == len(own) and s.get("state") != "waiting")
        if finished:
            key, pct = "done", 100
        elif not current_found:
            key, current_found = "current", True
        else:
            key = "waiting" if s.get("state") == "waiting" else "todo"
        if s.get("state") == "done":
            text = "done"
        elif s.get("state") == "waiting":
            text, pct = "waiting for the game", 0
        elif not own:
            text = "not started"
        else:
            text = f"{done} of {len(own)} done"
        rows.append((s, own, pct, text, key))
    if not current_found:  # everything is done: the marker stays on the last step
        s, own, pct, text, _ = rows[-1]
        rows[-1] = (s, own, pct, text, "current")
    return rows


def current_row(rows):
    return next((i, r) for i, r in enumerate(rows) if r[4] == "current")


def escape_markdown(text):
    """Issue text as inert Markdown for a table cell: no HTML, links, images, code spans, emphasis or autolinks."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"([\\`*_\[\]()!|#~{}+.:/@-])", r"\\\1", text)
    return " ".join(text.split())


def stage_label(step):
    return f"Stage {step['stage']}" + (f", plan phase {step['phase']}" if "phase" in step else "")


def where_in_roadmap(step):
    text = f"roadmap stage {step['stage']}, {STAGE_NAMES[step['stage']]}"
    return text + (f"; plan phase {step['phase']}" if "phase" in step else "")


def task_link(t, repo):
    return f"[{t['id']}](https://github.com/{repo}/issues/{t['issue']})" if t["issue"] else t["id"]


def render_markdown(tasks, repo, plan=None):
    rows = step_rows(tasks, plan)
    n, (step, own, _, text, _) = current_row(rows)
    counts = {s: sum(t["status"] == s for t in tasks) for s in STATUSES}
    lines = [
        START,
        "",
        f'<p align="center"><img src="{SVG}" alt="Progress: step {n + 1} of {len(rows)}, {escape(step["name"])}, '
        f'{text}" width="100%"></p>',
        "",
        f"**{MARKER} We are here: step {n + 1} of {len(rows)}, {step['name'].lower()}** "
        f"({where_in_roadmap(step)}): {text}. "
        "A step is done when its last task is merged, so the marker follows `main`, not the plans.",
        "",
        "| | Step | What it covers | Gate | Tasks |",
        "|---|---|---|---|---|",
    ]
    icons = {"done": "✅", "current": MARKER, "waiting": "⏸️", "todo": "⚪"}
    for i, (s, own, _, text, key) in enumerate(rows):
        detail = text
        if own and len(own) <= LIST_LIMIT and s.get("state") is None:
            detail += ": " + " · ".join(f"{ICON[t['status']]} {task_link(t, repo)}" for t in own)
        name = f"**{i + 1}. {s['name']}**"
        lines.append(f"| {icons[key]} | {name}<br><sub>{stage_label(s)}</sub> | {s['covers']} | "
                     f"{s.get('gate', '—')} | {detail} |")
    track = [t for t in tasks if t["step"] is None]
    lines += [
        "",
        f"{TRACK['name']} run alongside every step: {sum(t['status'] == 'done' for t in track)} of {len(track)} "
        "tasks done.",
        "",
        "<details>",
        f"<summary><b>All tasks</b>: {counts['done']} done, {counts['in review']} in review, "
        f"{counts['in progress']} in progress, {counts['ready']} ready, {counts['planned']} planned</summary>",
        "",
        "| | Task | Step | Size | Status |",
        "|---|---|---|---|---|",
    ]
    for t in tasks:
        # Roadmap and plan titles are maintainer-written Markdown; issue titles are anyone's text.
        title = t["title"] if t.get("trusted") else escape_markdown(t["title"])
        where = TRACK["name"] if t["step"] is None else f"{t['step'] + 1}. {rows[t['step']][0]['short']}"
        lines.append(f"| {ICON[t['status']]} | {task_link(t, repo)}: {title} | {where} | {t['size']} | "
                     f"{t['status']} |")
    lines += [
        "",
        "</details>",
        "",
        "<sub>Generated by `scripts/progress.py` from the task issues, "
        "[docs/implementation-plan.md](docs/implementation-plan.md) and [docs/roadmap.md](docs/roadmap.md). "
        "The reviewer session refreshes it; see "
        "[docs/maintainers.md](docs/maintainers.md#readme-progress).</sub>",
        "",
        END,
    ]
    return "\n".join(lines)


def render_svg(tasks, plan=None):
    """One bar across a dark card in the colours of the logo: a segment per step, a marker on the current one, and
    brackets for the roadmap stages under it."""
    rows = step_rows(tasks, plan)
    n, (step, _, _, text, _) = current_row(rows)
    width, left, gap = 880, 28, 6
    inner = width - 2 * left
    seg = (inner - gap * (len(rows) - 1)) / len(rows)
    bar_y, bar_h = 132, 18
    height = 252

    def x_of(i):
        return left + i * (seg + gap)

    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
        'role="img" aria-label="Sawgrass progress">',
        "<defs>",
        f'<linearGradient id="g" gradientUnits="userSpaceOnUse" x1="{left}" x2="{left + inner}" y1="0" y2="0">'
        '<stop offset="0" stop-color="#14e1f0"/><stop offset="1" stop-color="#7cf000"/></linearGradient>',
        "</defs>",
        "<style>text{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif}"
        ".h{font-size:22px;font-weight:700;fill:#e8fff4}.s{font-size:14px;fill:#8fb3a6}"
        ".l{font-size:13px;font-weight:600;fill:#c9e6db}.c{font-size:13px;font-weight:700;fill:#a6ff4d}"
        ".n{font-size:11px;fill:#7d9a90}.w{font-size:11px;fill:#5fe3f0}"
        ".m{font-size:11px;font-weight:700;fill:#060a08;letter-spacing:1px}"
        ".b{font-size:12px;fill:#8fb3a6}</style>",
        f'<rect width="{width}" height="{height}" rx="16" fill="#060a08"/>',
        f'<rect x="1" y="1" width="{width - 2}" height="{height - 2}" rx="15" fill="none" stroke="#1d3b2f"/>',
        f'<text x="{left}" y="44" class="h">We are here: {escape(step["name"])}</text>',
        f'<text x="{left}" y="68" class="s">Step {n + 1} of {len(rows)} · {escape(where_in_roadmap(step))} · '
        f'{escape(text)}</text>',
    ]
    for i, (s, _, pct, text, key) in enumerate(rows):
        x = x_of(i)
        if key == "waiting":
            out.append(f'<rect x="{x + 0.5:.1f}" y="{bar_y + 0.5}" width="{seg - 1:.1f}" height="{bar_h - 1}" rx="5" '
                       'fill="none" stroke="#2b6f78" stroke-dasharray="4 3"/>')
        else:
            out.append(f'<rect x="{x:.1f}" y="{bar_y}" width="{seg:.1f}" height="{bar_h}" rx="5" fill="#13201b"/>')
        if pct:
            out.append(f'<rect x="{x:.1f}" y="{bar_y}" width="{seg * pct / 100:.1f}" height="{bar_h}" rx="5" '
                       'fill="url(#g)"/>')
        cx = x + seg / 2
        if key == "current":
            out.append(f'<rect x="{x - 2:.1f}" y="{bar_y - 2}" width="{seg + 4:.1f}" height="{bar_h + 4}" rx="7" '
                       'fill="none" stroke="#a6ff4d" stroke-width="1.5"/>')
            pill_w = 96
            px = min(max(cx - pill_w / 2, left), left + inner - pill_w)
            out.append(f'<rect x="{px:.1f}" y="92" width="{pill_w}" height="22" rx="11" fill="#a6ff4d"/>')
            out.append(f'<text x="{px + pill_w / 2:.1f}" y="107" class="m" text-anchor="middle">WE ARE HERE</text>')
            out.append(f'<path d="M{cx - 6:.1f} 114 L{cx + 6:.1f} 114 L{cx:.1f} 122 Z" fill="#a6ff4d"/>')
        label = "c" if key == "current" else "l"
        out.append(f'<text x="{cx:.1f}" y="{bar_y + 38}" class="{label}" text-anchor="middle">'
                   f'{i + 1}. {escape(s["short"])}</text>')
        small = {"waiting for the game": "waiting"}.get(text, text)
        out.append(f'<text x="{cx:.1f}" y="{bar_y + 54}" class="{"w" if key == "waiting" else "n"}" '
                   f'text-anchor="middle">{escape(small)}</text>')
    # Brackets for the roadmap stages: one per run of steps with the same stage.
    y = bar_y + 72
    i = 0
    while i < len(rows):
        j = i
        while j + 1 < len(rows) and rows[j + 1][0]["stage"] == rows[i][0]["stage"]:
            j += 1
        x0, x1 = x_of(i) + 2, x_of(j) + seg - 2
        out.append(f'<path d="M{x0:.1f} {y - 6} L{x0:.1f} {y} L{x1:.1f} {y} L{x1:.1f} {y - 6}" fill="none" '
                   'stroke="#2a4a3d"/>')
        stage = rows[i][0]["stage"]
        name = f"Stage {stage}" + (f" · {STAGE_NAMES[stage]}" if j - i >= 2 else "")
        out.append(f'<text x="{(x0 + x1) / 2:.1f}" y="{y + 18}" class="b" text-anchor="middle">{escape(name)}</text>')
        i = j + 1
    out.append("</svg>")
    return "\n".join(out) + "\n"


def splice(readme, block):
    """README text with the part between the markers replaced by `block` (which includes the markers)."""
    start, end = readme.find(START), readme.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{README} has no progress markers")
    return readme[:start] + block + readme[end + len(END):]


def _gh_items(repo):
    items, page = [], 1
    while True:
        out = subprocess.run(["gh", "api", f"repos/{repo}/issues?state=all&per_page=100&page={page}"],
                             check=True, capture_output=True, text=True).stdout
        batch = json.loads(out)
        items += batch
        if len(batch) < 100:
            return items
        page += 1


def _read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def _write(path, text):
    with open(os.path.join(ROOT, path), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--issues", help="JSON file with issues as /repos/OWNER/REPO/issues returns them")
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "sawgrass-mp/sawgrass"))
    args = parser.parse_args(argv)

    if args.issues:
        with open(args.issues, encoding="utf-8") as f:
            items = json.load(f)
    else:
        items = _gh_items(args.repo)
    plan = plan_tasks(_read(PLAN))
    tasks = collect(items, roadmap_tasks(_read(ROADMAP)), plan)
    block, svg = render_markdown(tasks, args.repo, plan), render_svg(tasks, plan)

    if not (args.write or args.check):
        print(block)
        return 0
    readme = _read(README)
    new_readme = splice(readme, block)
    old_svg = _read(SVG) if os.path.exists(os.path.join(ROOT, SVG)) else ""
    if args.check:
        stale = [p for p, old, new in ((README, readme, new_readme), (SVG, old_svg, svg)) if old != new]
        for p in stale:
            print(f"{p} is stale: run python3 -I scripts/progress.py --write")
        return 1 if stale else 0
    _write(README, new_readme)
    _write(SVG, svg)
    print(f"Wrote {README} and {SVG}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
