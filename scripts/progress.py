"""Generate the progress section of README.md and docs/assets/progress.svg. Standard library only.

    python3 -I scripts/progress.py            # print the generated section
    python3 -I scripts/progress.py --write    # rewrite README.md between the markers and docs/assets/progress.svg
    python3 -I scripts/progress.py --check    # exit 1 if README.md or the SVG differs from what --write would write
    python3 -I scripts/progress.py --issues FILE ...   # read issues from a JSON file instead of the GitHub API

The data comes from two places, never from hand edits:

- the task issues (title `AREA-N: ...`) and the open pull requests, read through the `gh` command line tool;
- the task table in docs/roadmap.md, for tasks that have no issue yet and as a fallback for sizes.

A task is `done` when its issue is closed as completed, `in review` when an open pull request carries its ID,
`in progress` when it is labelled `claimed`, `ready` when labelled `ready`, and `planned` otherwise. Issues closed
as not planned are left out. Progress is weighted by size: S = 1, M = 3, L = 8.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from xml.sax.saxutils import escape

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
README = "README.md"
SVG = "docs/assets/progress.svg"
ROADMAP = "docs/roadmap.md"
START = "<!-- progress:start (generated by scripts/progress.py; do not edit by hand) -->"
END = "<!-- progress:end -->"

AREAS = "NET|SRV|IM|DB|SCRIPT|RP|BOT|CLIENT|LAUNCH|OPS|DOC"
TASK_TITLE = re.compile(rf"^((?:{AREAS})-[0-9]+): (.+)$")
ROADMAP_ROW = re.compile(rf"^\|\s*((?:{AREAS})-[0-9]+)\s*\|\s*(.+?)\s*\|\s*([SML])\s*\|\s*$")

WEIGHT = {"S": 1, "M": 3, "L": 8}
DEFAULT_SIZE = "M"

# Order matters: the first status in this tuple is the furthest along.
STATUSES = ("done", "in review", "in progress", "ready", "planned")
ICON = {"done": "✅", "in review": "🔍", "in progress": "🛠️", "ready": "🟢", "planned": "⚪"}

# Roadmap stages (docs/roadmap.md). `areas` are the task prefixes that count towards a stage. A stage with a fixed
# `state` shows that text instead of a computed bar.
STAGES = (
    {"n": 0, "name": "Repository foundation", "areas": (), "state": "done",
     "note": "Rules, CI, claim bot, review agent"},
    {"n": 1, "name": "Server without the game", "areas": ("NET", "SRV", "IM", "BOT"),
     "note": "Gates: 1000 bots on one machine, then 4096"},
    {"n": 2, "name": "Roleplay base", "areas": ("DB", "SCRIPT", "RP"),
     "note": "PostgreSQL, scripting, characters, money, jobs"},
    {"n": 3, "name": "Client in the game", "areas": ("CLIENT",), "state": "waiting",
     "note": "Waits until the game boots on PC through Leonida"},
    {"n": 4, "name": "Launcher and releases", "areas": ("LAUNCH",),
     "note": "Signing, auto-update, server list"},
    {"n": 5, "name": "Scale", "areas": (),
     "note": "Real players; zones only if measurements call for them"},
)
TRACK = {"name": "Tooling and docs", "areas": ("OPS", "DOC"), "note": "CI gates, review agent, documentation"}


def area(task_id):
    return task_id.split("-", 1)[0]


def size_from_labels(labels):
    for label in labels:
        m = re.fullmatch(r"size: ([SML])", label)
        if m:
            return m.group(1)
    return None


def roadmap_tasks(text):
    """{id: (title, size)} from the task table of docs/roadmap.md."""
    tasks = {}
    for line in text.splitlines():
        m = ROADMAP_ROW.match(line.strip())
        if m:
            tasks[m.group(1)] = (m.group(2), m.group(3))
    return tasks


def collect(items, roadmap):
    """Tasks as a list of dicts (id, title, size, status, issue), sorted by stage order and ID.

    `items` are issues as the REST API returns them from /issues (pull requests included, marked by the
    `pull_request` key). `roadmap` is the result of roadmap_tasks().
    """
    in_review = set()
    issues = []
    for item in items:
        m = TASK_TITLE.match((item.get("title") or "").strip())
        if not m:
            continue
        if "pull_request" in item:
            if item.get("state") == "open" and not item.get("draft"):
                in_review.add(m.group(1))
            continue
        if item.get("state") == "closed" and item.get("state_reason") == "not_planned":
            continue
        issues.append((m.group(1), m.group(2).strip(), item))

    tasks = {}
    for task_id, title, item in issues:
        labels = {label["name"] if isinstance(label, dict) else label for label in item.get("labels", [])}
        if item.get("state") == "closed":
            status = "done"
        elif task_id in in_review:
            status = "in review"
        elif "claimed" in labels:
            status = "in progress"
        elif "ready" in labels:
            status = "ready"
        else:
            status = "planned"
        size = size_from_labels(labels) or roadmap.get(task_id, (None, DEFAULT_SIZE))[1]
        task = {"id": task_id, "title": title, "size": size, "status": status, "issue": item.get("number")}
        # Two issues with one ID: an open one wins over a closed one, so reopened work is not shown as done.
        old = tasks.get(task_id)
        if old is None or (old["status"] == "done" and status != "done"):
            tasks[task_id] = task

    for task_id, (title, size) in roadmap.items():
        if task_id not in tasks:
            status = "in review" if task_id in in_review else "planned"
            tasks[task_id] = {"id": task_id, "title": title, "size": size, "status": status, "issue": None}

    order = [a for s in STAGES for a in s["areas"]] + list(TRACK["areas"])
    return sorted(tasks.values(), key=lambda t: (order.index(area(t["id"])), int(t["id"].split("-")[1])))


def progress(tasks):
    """(done weight, total weight, percent rounded down)."""
    total = sum(WEIGHT[t["size"]] for t in tasks)
    done = sum(WEIGHT[t["size"]] for t in tasks if t["status"] == "done")
    return done, total, (100 * done // total if total else 0)


def groups(tasks):
    """Rows for the stage table: (label, note, tasks or None, fixed state or None)."""
    rows = []
    for s in STAGES:
        own = [t for t in tasks if area(t["id"]) in s["areas"]]
        rows.append((f"Stage {s['n']}: {s['name']}", s["note"], own, s.get("state")))
    rows.append((TRACK["name"], TRACK["note"], [t for t in tasks if area(t["id"]) in TRACK["areas"]], None))
    return rows


def current_stage(tasks):
    """The first stage that is neither done nor waiting and has unfinished or no tasks."""
    for s in STAGES:
        if s.get("state") in ("done", "waiting"):
            continue
        own = [t for t in tasks if area(t["id"]) in s["areas"]]
        if not own or any(t["status"] != "done" for t in own):
            return s
    return STAGES[-1]


def bar(percent, cells=20):
    filled = round(percent * cells / 100)
    return "█" * filled + "░" * (cells - filled)


def state_text(own, fixed):
    if fixed == "done":
        return 100, "done"
    if fixed == "waiting":
        return 0, "waiting for the game"
    if not own:
        return 0, "not started"
    _, _, pct = progress(own)
    done = sum(t["status"] == "done" for t in own)
    return pct, f"{done} of {len(own)} task{'s' if len(own) != 1 else ''} done"


def render_markdown(tasks, repo):
    _, _, overall = progress(tasks)
    stage = current_stage(tasks)
    counts = {s: sum(t["status"] == s for t in tasks) for s in STATUSES}
    lines = [
        START,
        "",
        f'<p align="center"><img src="{SVG}" alt="Progress: stage {stage["n"]}, {overall}% of the planned tasks '
        f'done" width="100%"></p>',
        "",
        f"**Current stage: {stage['n']}, {stage['name'].lower()}.** {overall}% of the planned tasks are done, "
        "weighted by size (S = 1, M = 3, L = 8). New tasks are added as stages open, so the percentage measures "
        "the work planned so far, not the distance to a release.",
        "",
        "| Stage | Progress | State |",
        "|---|---|---|",
    ]
    for label, note, own, fixed in groups(tasks):
        pct, text = state_text(own, fixed)
        lines.append(f"| **{label}**<br><sub>{note}</sub> | `{bar(pct)}` {pct}% | {text} |")
    lines += [
        "",
        "<details open>",
        f"<summary><b>Tasks</b>: {counts['done']} done, {counts['in review']} in review, "
        f"{counts['in progress']} in progress, {counts['ready']} ready, {counts['planned']} planned</summary>",
        "",
        "| | Task | Size | Status |",
        "|---|---|---|---|",
    ]
    for t in tasks:
        link = f"[{t['id']}](https://github.com/{repo}/issues/{t['issue']})" if t["issue"] else t["id"]
        title = t["title"].replace("|", "\\|")
        lines.append(f"| {ICON[t['status']]} | {link}: {title} | {t['size']} | {t['status']} |")
    lines += [
        "",
        "</details>",
        "",
        "<sub>Generated by `scripts/progress.py` from the task issues and "
        "[docs/roadmap.md](docs/roadmap.md). The reviewer session refreshes it; see "
        "[docs/maintainers.md](docs/maintainers.md#readme-progress).</sub>",
        "",
        END,
    ]
    return "\n".join(lines)


def render_svg(tasks):
    """A dark card with one gradient bar per stage, in the colours of the logo."""
    _, _, overall = progress(tasks)
    stage = current_stage(tasks)
    rows = groups(tasks)
    width, top, row_h = 880, 132, 46
    height = top + row_h * len(rows) + 24
    bar_x, bar_w = 360, 380
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
        'role="img" aria-label="Sawgrass progress">',
        "<defs>",
        '<linearGradient id="g" x1="0" x2="1" y1="0" y2="0">'
        '<stop offset="0" stop-color="#14e1f0"/><stop offset="1" stop-color="#7cf000"/></linearGradient>',
        "</defs>",
        "<style>text{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif}"
        ".h{font-size:22px;font-weight:700;fill:#e8fff4}.s{font-size:14px;fill:#8fb3a6}"
        ".l{font-size:15px;font-weight:600;fill:#e8fff4}.n{font-size:12px;fill:#7d9a90}"
        ".p{font-size:14px;font-weight:700;fill:#a6ff4d}.w{font-size:13px;fill:#5fe3f0}</style>",
        f'<rect width="{width}" height="{height}" rx="16" fill="#060a08"/>',
        f'<rect x="1" y="1" width="{width - 2}" height="{height - 2}" rx="15" fill="none" stroke="#1d3b2f"/>',
        f'<text x="28" y="44" class="h">Stage {stage["n"]}: {escape(stage["name"])}</text>',
        f'<text x="28" y="68" class="s">{overall}% of the planned tasks done, weighted by size</text>',
        f'<rect x="28" y="84" width="{width - 56}" height="14" rx="7" fill="#13201b"/>',
    ]
    if overall:
        out.append(f'<rect x="28" y="84" width="{(width - 56) * overall / 100:.1f}" height="14" rx="7" fill="url(#g)"/>')
    for i, (label, note, own, fixed) in enumerate(rows):
        y = top + i * row_h
        pct, text = state_text(own, fixed)
        out.append(f'<text x="28" y="{y + 14}" class="l">{escape(label)}</text>')
        out.append(f'<text x="28" y="{y + 32}" class="n">{escape(note)}</text>')
        out.append(f'<rect x="{bar_x}" y="{y + 4}" width="{bar_w}" height="10" rx="5" fill="#13201b"/>')
        if pct:
            out.append(f'<rect x="{bar_x}" y="{y + 4}" width="{bar_w * pct / 100:.1f}" height="10" rx="5" '
                       'fill="url(#g)"/>')
        out.append(f'<text x="{bar_x}" y="{y + 32}" class="n">{escape(text)}</text>')
        if fixed == "waiting":
            out.append(f'<text x="{width - 28}" y="{y + 14}" class="w" text-anchor="end">waiting</text>')
        else:
            out.append(f'<text x="{width - 28}" y="{y + 14}" class="p" text-anchor="end">{pct}%</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def splice(readme, block):
    """README text with the part between the markers replaced by `block` (which includes the markers)."""
    start, end = readme.find(START), readme.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{README} has no progress markers")
    return readme[:start] + block + readme[end + len(END):]


def _gh_items(repo):
    items, page = [], 1
    while True:
        out = subprocess.run(["gh", "api", f"repos/{repo}/issues?state=all&per_page=100&page={page}"],
                             check=True, capture_output=True, text=True).stdout
        batch = json.loads(out)
        items += batch
        if len(batch) < 100:
            return items
        page += 1


def _read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def _write(path, text):
    with open(os.path.join(ROOT, path), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--issues", help="JSON file with issues as /repos/OWNER/REPO/issues returns them")
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "sawgrass-mp/sawgrass"))
    args = parser.parse_args(argv)

    if args.issues:
        with open(args.issues, encoding="utf-8") as f:
            items = json.load(f)
    else:
        items = _gh_items(args.repo)
    tasks = collect(items, roadmap_tasks(_read(ROADMAP)))
    block, svg = render_markdown(tasks, args.repo), render_svg(tasks)

    if not (args.write or args.check):
        print(block)
        return 0
    readme = _read(README)
    new_readme = splice(readme, block)
    old_svg = _read(SVG) if os.path.exists(os.path.join(ROOT, SVG)) else ""
    if args.check:
        stale = [p for p, old, new in ((README, readme, new_readme), (SVG, old_svg, svg)) if old != new]
        for p in stale:
            print(f"{p} is stale: run python3 -I scripts/progress.py --write")
        return 1 if stale else 0
    _write(README, new_readme)
    _write(SVG, svg)
    print(f"Wrote {README} and {SVG}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
